# ==========================================
# Simple ASM Demo Program
# ==========================================

# ------------------------------------------
# Set up register A
# ------------------------------------------

adda
adda
adda
adda
# A = 4


# ------------------------------------------
# Set up register B
# ------------------------------------------

addb
addb
# B = 2


# ------------------------------------------
# Add B to A
# ------------------------------------------

add
# A = 4 + 2
# A = 6


# ------------------------------------------
# Save A on the stack
# ------------------------------------------

pusha


# ------------------------------------------
# Change A
# ------------------------------------------

adda
adda
# A = 8


# ------------------------------------------
# Restore the old A
# ------------------------------------------

popa
# A = 6


# ------------------------------------------
# Make A and B equal
# ------------------------------------------

addb
addb
addb
addb
# B = 6


# ------------------------------------------
# Check if A == B
# ------------------------------------------

cmp

# This executes because A == B
adda
# A = 7

endif


# ------------------------------------------
# Change B so it is different
# ------------------------------------------

addb
# B = 7

# A == B again
cmp

# This executes
add
# A = 14

endif


# ------------------------------------------
# Test a failed comparison
# ------------------------------------------

addb
# B = 8

cmp

# These instructions are ignored
# because A != B

adda
adda
add
pusha

endif


# ------------------------------------------
# Program finished
# ------------------------------------------